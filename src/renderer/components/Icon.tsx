export type IconName = keyof typeof ICONS;

const SIZE = { xs: 12, sm: 14, md: 16, lg: 20 } as const;

export function Icon({
  name,
  size = 'sm',
  className,
  strokeWidth = 2,
}: {
  name: IconName;
  size?: keyof typeof SIZE;
  className?: string;
  strokeWidth?: number;
}) {
  const C = ICONS[name];
  return <C className={`icon${className ? ` ${className}` : ''}`} size={SIZE[size]} strokeWidth={strokeWidth} aria-hidden focusable={false} />;
}
